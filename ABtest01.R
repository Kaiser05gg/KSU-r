# Section 2：サイコロの期待値と分散
############################################################

x <- 1:6                 # サイコロの目
p <- rep(1/6, 6)         # 1/6 が6つ

# 期待値
mu <- sum(x * p)

# 分散（E[X^2] - E[X]^2）
v <- sum((x^2) * p) - mu^2

cat("E[X]=", mu, " Var[X]=", v, "\n")



