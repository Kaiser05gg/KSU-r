# Section 3：サマージャンボ宝くじの期待値
############################################################

# 当選金額
prize <- c(5e8, 1e8, 1e5, 1e7, 1e6, 1e5, 3000, 300, 0)

# 当選確率
prob <- c(1/10000000, 4/10000000, 30/10000000,
          1/100000, 4/100000, 1/10000,
          1000/10000, 2000/10000, 1 - (1/10000000 + 4/10000000 +
          30/10000000 + 1/100000 + 4/100000 +
          1/10000 + 1000/10000 + 2000/10000))

# 期待値
mu <- sum(prize * prob)

cat("E[当選金額]=", mu, "\n")



