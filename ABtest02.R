############################################################
# Section 9：Z検定（両側、分散既知、α=0.05）
############################################################

set.seed(NULL)

alpha <- 0.05       # 有意水準
mu0 <- 0.5          # 帰無仮説の平均
sigma <- sqrt(0.25) # 分散=0.25 → sd=0.5
n <- 50             # 標本サイズ

# 範囲：標本平均の正規分布
crit <- qnorm(c(alpha/2, 1-alpha/2), mean = mu0, sd = sigma / sqrt(n))

cat("両側棄却域：", crit, "\n")

# 実際に標本平均を1つ生成
xbar <- mean(rbinom(n, 1, mu0))
cat("標本平均=", xbar, "\n")

# 棄却かどうか
if (xbar < crit[1] || xbar > crit[2]) {
  cat("→ H0 を棄却（有意差あり）\n")
} else {
  cat("→ H0 を採択（有意差なし）\n")
}


############################################################
# Section 10：有意水準 α の可視化（参考）
############################################################

x <- seq(-4, 4, length = 400)

plot(x, dnorm(x), type = "l", lwd = 2,
     main = "標準正規分布と α の可視化")

for (a in c(0.1, 0.05, 0.01)) {
  crit <- qnorm(c(a/2, 1 - a/2))
  lines(x, dnorm(x), col = "black")
  abline(v = crit, col = "red", lty = 2)
  legend("topright", legend = paste("alpha =", a),
         lty = 2, bty = "n")
  cat("alpha=", a, " → 棄却域=", crit, "\n")
}


