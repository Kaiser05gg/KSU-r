############################################################
# Section 1：潜在結果（Potential Outcomes）を用いたABテストのシミュレーション
############################################################

# 広告Aを見た場合の滞在時間（Y(1)）：正規分布 N(10, 2^2)
y_a <- rnorm(2000, mean = 10, sd = 2)

# 広告Bを見た場合の滞在時間（Y(0)）：正規分布 N(8, 2^2)
y_b <- rnorm(2000, mean = 8, sd = 2)

# 平均を確認
mean(y_a)   # 約10
mean(y_b)   # 約8

############################################################
# Section 2：ランダム化（割付け）を行う
############################################################

set.seed(1)

n <- 2000

# 0 or 1 をランダムに振る（ベルヌーイ分布 p=0.5）
# 1なら広告A、0なら広告B
Tr <- rbinom(n, 1, 0.5)
print(Tr)



############################################################
# Section 3：観測されるデータの生成（潜在結果から観測値を作る）
############################################################

# 広告A を見たユーザーの観測データ
data_a <- y_a[Tr == 1]

# 広告B を見たユーザーの観測データ
data_b <- y_b[Tr == 0]

print(data_a)
print(data_b)

############################################################
# Section 4：観測された平均効果（Difference in Means）
############################################################

cat("広告Aグループの平均滞在時間 =", mean(y_a[Tr == 1]), "\n")
cat("広告Bグループの平均滞在時間 =", mean(y_b[Tr == 0]), "\n")
cat("平均の差（推定効果） =", mean(y_a[Tr == 1]) - mean(y_b[Tr == 0]), "\n")

# 真の因果効果（平均因果効果）
cat("真の ATE =", mean(y_a - y_b), "\n")


############################################################
# Section 5：潜在結果 Y(0), Y(1) の分布を可視化
############################################################

set.seed(2)

n <- 2000
y0 <- rnorm(n, mean = 8, sd = 2)   # Y(0)
y1 <- rnorm(n, mean = 10, sd = 2)  # Y(1)

plot(density(y0), col = "blue", lwd = 2, main = "潜在結果の密度関数")
lines(density(y1), col = "red", lwd = 2)
legend("topright", legend = c("Y(0)", "Y(1)"),
       col = c("blue", "red"), lty = 1, bty = "n")

cat("E[Y(0)] =", mean(y0), "\n")
cat("E[Y(1)] =", mean(y1), "\n")
cat("ATE =", mean(y1 - y0), "\n")


############################################################
# Section 6：（発展）ランダム化されていない場合の問題点
############################################################

# 「広告Aを見やすい人」「広告Bしか見ていない人」が偏ってしまう状況をシミュレーション

set.seed(10)

n <- 2000

# 潜在結果は同じ
y0 <- rnorm(n, mean = 8, sd = 2)
y1 <- rnorm(n, mean = 10, sd = 2)

# ランダム化ではなく「潜在結果に依存したバイアスのある割当て」
# 例：滞在時間がもともと長い人ほど広告Aを見る確率が高い
pTr <- pnorm((y1 + y0)/2, mean = 8, sd = 2)   # 0〜1 の確率を生成
Tnr <- rbinom(n, 1, pTr)                      # バイアス割付け

# グループごとの平均を比較（偏って推定される！）
cat("非ランダム化の A グループ平均 =", mean(y1[Tnr == 1]), "\n")
cat("非ランダム化の B グループ平均 =", mean(y0[Tnr == 0]), "\n")
cat("観測された平均の差 =", mean(y1[Tnr == 1]) - mean(y0[Tnr == 0]), "\n")

# 真の因果効果（ATE）は変わらない
cat("真の ATE =", mean(y1 - y0), "\n")

# → 差が大きくズレる（バイアスがある）


############################################################
# Section 7：結果のまとめ（コメント用）
