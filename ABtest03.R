# ・ランダム化があると、平均の差は真の因果効果の良い推定量になる
# ・ランダム化がないと、グループ差は潜在結果に依存し、推定値がバイアスを持つ
# ・ABテストの本質は「ランダム化によって交絡を断つ」こと
