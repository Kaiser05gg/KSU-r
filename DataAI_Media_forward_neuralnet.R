############################################################
# Section 3: データの準備（XOR問題）
############################################################

# 入力データ（XOR）
X <- matrix(
  c(0,0,
    0,1,
    1,0,
    1,1),
  ncol = 2,
  byrow = TRUE
)

# 教師ラベル（0/1）
y <- c(0, 1, 1, 0)

print(X)
print(y)


############################################################
# Section 4: 活性化関数の定義
############################################################

# シグモイド関数
sigmoid <- function(x) {
  1 / (1 + exp(-x))
}


############################################################
# Section 5: ネットワーク構造の定義
############################################################

# 入力層：2
# 中間層：2
# 出力層：1

set.seed(1)

# 重み（入力層 → 中間層）
W1 <- matrix(runif(4, -1, 1), nrow = 2)

# バイアス（中間層）
b1 <- runif(2, -1, 1)

# 重み（中間層 → 出力層）
W2 <- runif(2, -1, 1)

# バイアス（出力層）
b2 <- runif(1, -1, 1)

W1; b1; W2; b2


############################################################
# Section 6: フォワード計算（順伝播）
############################################################

forward <- function(x) {
  
  # 中間層
  z1 <- sigmoid(W1 %*% x + b1)
  
  # 出力層
  z2 <- sigmoid(sum(W2 * z1) + b2)
  
  return(z2)
}

# 各データ点に対する出力
apply(X, 1, forward)


############################################################
# Section 7: 出力結果の確認
############################################################

pred <- apply(X, 1, forward)

# 0.5 を閾値としてクラス分類
pred_class <- ifelse(pred >= 0.5, 1, 0)

pred
pred_class
y


############################################################
# Section 8: 可視化（参考）
############################################################

plot(1:4, pred,
