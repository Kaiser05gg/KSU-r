# Section 2: 活性化関数の定義
############################################################

# シグモイド関数（中間層で使用）
sigmoid_func <- function(x){
  1 / (1 + exp(-x))
}

# 恒等関数（出力層で使用）
identity_func <- function(x){
  x
}


############################################################
# Section 3: パラメータ（重み・バイアス）の定義
############################################################

# 各層の重み・バイアスを tibble で定義
params <- list(
  W1 = tibble(
    w1 = c(0.1, 0.2),
    w2 = c(0.3, 0.4)
  ),
  B1 = tibble(
    b1 = 0.1,
    b2 = 0.2
  ),
  W2 = tibble(
    w1 = c(0.5, 0.6),
    w2 = c(0.7, 0.8)
  ),
  B2 = tibble(
    b1 = 0.1,
    b2 = 0.2
  ),
  W3 = tibble(
    w1 = c(0.1, 0.2),
    w2 = c(0.3, 0.4)
  ),
  B3 = tibble(
    b1 = 0.1,
    b2 = 0.2
  )
)


############################################################
# Section 4: フォワード型ニューラルネットワーク
############################################################

forward_network <- function(X, params){
  
  # --- パラメータ読み込み ---
  W1 <- as.matrix(params$W1)
  B1 <- as.matrix(params$B1)
  W2 <- as.matrix(params$W2)
  B2 <- as.matrix(params$B2)
  W3 <- as.matrix(params$W3)
  B3 <- as.matrix(params$B3)
  
  # --- 第1層 ---
  A1 <- X %*% W1 + B1
  Z1 <- sigmoid_func(A1)
  
  # --- 第2層 ---
  A2 <- Z1 %*% W2 + B2
  Z2 <- sigmoid_func(A2)
  
  # --- 出力層 ---
  A3 <- Z2 %*% W3 + B3
  Y  <- identity_func(A3) %>%
    as_tibble() %>%
    rename(y1 = V1, y2 = V2)
  
  return(Y)
}


############################################################
# Section 5: 入力データの定義
############################################################

# 入力（1サンプル）
X <- matrix(c(1, 0.5), nrow = 1)
X


############################################################
# Section 6: フォワード計算の実行
############################################################

forward_network(X, params)


############################################################
# Section 7: Softmax関数の定義
############################################################

softmax_func <- function(a){
  # 数値安定化（最大値を引く）
  a_shift <- a - max(a)
  exp_a <- exp(a_shift)
  exp_a / sum(exp_a)
}


