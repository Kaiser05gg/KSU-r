# ・「データ → 特徴量 → 予測」という流れを理解する
# ・線形分離可能／不可能の違いを理解する


############################################################
# Section 3: データの準備
############################################################

# 2次元の簡単な人工データを作成する
# x1, x2 が特徴量、y がラベル（-1, +1）

set.seed(1)

x1 <- c(1, 2, 3, 4, 5, 6)
x2 <- c(1, 1, 2, 3, 3, 4)
y  <- c(-1, -1, -1, 1, 1, 1)

# データを行列としてまとめる
X <- cbind(x1, x2)
print(X)
print(y)


############################################################
# Section 4: パーセプトロンの初期設定
############################################################

# 重みベクトル w（初期値）
w <- c(0, 0)

# バイアス b
b <- 0

# 学習率
eta <- 1

# エポック数（データを何周するか）
epoch <- 10


############################################################
# Section 5: パーセプトロンの学習ループ
############################################################

for (e in 1:epoch) {
  
  cat("epoch =", e, "\n")
  
  for (i in 1:nrow(X)) {
    
    # 内積 + バイアス
    u <- sum(w * X[i, ]) + b
    
    # 予測（符号関数）
    y_hat <- ifelse(u >= 0, 1, -1)
    
    # 間違えたら更新
    if (y_hat != y[i]) {
      w <- w + eta * y[i] * X[i, ]
      b <- b + eta * y[i]
    }
    
    cat(" data", i,
        "u =", u,
        "y_hat =", y_hat,
        "w =", w,
        "b =", b, "\n")
  }
  
  cat("----\n")
}


############################################################
# Section 6: 学習後の分類結果の確認
############################################################

# 学習後の重み・バイアス
cat("final w =", w, " b =", b, "\n")

# 各データ点の予測
pred <- apply(X, 1, function(x){
  ifelse(sum(w * x) + b >= 0, 1, -1)
})

pred
y


############################################################
# Section 7: 可視化（データと決定境界）
############################################################

# データ点をプロット
plot(X[,1], X[,2],
     col = ifelse(y == 1, "red", "blue"),
     pch = 19,
     xlab = "x1",
     ylab = "x2",
     main = "Perceptron classification")

# 決定境界：w1*x1 + w2*x2 + b = 0
# x2 = -(w1*x1 + b)/w2

abline(a = -b / w[2],
       b = -w[1] / w[2],
       lwd = 2)


