     pch = 19,
     xlab = "x1",
     ylab = "x2",
     main = "Perceptron on XOR data")

# 決定境界（存在すると仮定した直線）
# 実際には XOR は1本の直線では分離できない
if (w[2] != 0) {
  abline(a = -b / w[2],
         b = -w[1] / w[2],
         lwd = 2)
}


