############################################################
# Section 3: XORデータの作成（線形分離不可能）
############################################################

# 特徴量（2次元）
X <- matrix(
  c(0,0,
    0,1,
    1,0,
    1,1),
  ncol = 2,
  byrow = TRUE
)

# ラベル（XOR）
# 同じ値同士 → -1、異なる値 → +1
y <- c(-1, 1, 1, -1)

print(X)
print(y)


############################################################
# Section 4: データの可視化
############################################################

plot(X[,1], X[,2],
     col = ifelse(y == 1, "red", "blue"),
     pch = 19,
     xlab = "x1",
     ylab = "x2",
     main = "XOR data (not linearly separable)")
grid()


############################################################
# Section 5: パーセプトロンの初期設定
############################################################

w <- c(0, 0)   # 重み
b <- 0         # バイアス
eta <- 1       # 学習率
epoch <- 20    # エポック数


############################################################
# Section 6: パーセプトロン学習ループ
############################################################

for (e in 1:epoch) {
  
  cat("epoch =", e, "\n")
  
  for (i in 1:nrow(X)) {
    
    # 線形結合
    u <- sum(w * X[i, ]) + b
    
    # 予測
    y_hat <- ifelse(u >= 0, 1, -1)
    
    # 間違えたら更新
    if (y_hat != y[i]) {
      w <- w + eta * y[i] * X[i, ]
      b <- b + eta * y[i]
    }
    
    cat(" data", i,
        "u =", u,
        "y_hat =", y_hat,
        "w =", w,
        "b =", b, "\n")
  }
  
  cat("----\n")
}


############################################################
# Section 7: 学習結果の確認
############################################################

cat("final w =", w, " b =", b, "\n")

# 各点の予測
pred <- apply(X, 1, function(x){
  ifelse(sum(w * x) + b >= 0, 1, -1)
})

pred
y


############################################################
# Section 8: 決定境界の描画（参考）
