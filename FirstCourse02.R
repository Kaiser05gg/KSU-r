csvurl <- "https://www.cc.kyoto-su.ac.jp/~ogohara/lecture/DataAI_FirstCourse/DATA_1min.csv"

# DATA_1min.csv として保存
download.file(csvurl, destfile = "DATA_1min.csv")


############################################################
# Section 4: CSV読み込み（第1版）
############################################################

# 最初の読み込み例（気象計測データ）
# date, temp（気温）, rh（湿度）, pre（気圧）, ws（風速）, wd（風向）など
df <- read_csv(
  "DATA_1min.csv",
  locale = locale(encoding = "Shift_JIS"),
  col_names = c("date", "temp", "rh", "pre", "spre", "ws", "wd", "maxws", "maxwd", "irad"),
  skip = 1
)

df    # 中身を確認


############################################################
# Section 5: 日付型を正確に解釈して読み込み（改良版）
############################################################

df <- read_csv(
  "DATA_1min.csv",
  locale = locale(encoding = "Shift_JIS"),
  skip = 1,
  col_types = cols(date = col_datetime(format = "%Y/%m/%d %H:%M"))
)

df    # 再度確認（date 列がPOSIXctになる）


############################################################
# Section 6: 風向データ（日本語方位）を角度に変換する準備
############################################################

# 16方向の日本語方位
wds <- c(
  "北北東", "北東", "東北東", "東",
  "東南東", "南東", "南南東", "南",
  "南南西", "南西", "西南西", "西",
  "西北西", "北西", "北北西", "北"
)

# 方角を 0〜360度に変換（22.5度刻み）
wdf <- 1:16
wdf <- (wdf * 22.5) %% 360

wdf    # → 各方位に対応する角度一覧


############################################################
# Section 7: 方位 → 角度 変換の基本
############################################################

wds == "東"                   # "東" が TRUE となる位置
which(wds == "東")           # "東" のインデックス取得
wdf[which(wds == "東")]      # "東" に対応する角度 ＝ 90度


############################################################
# Section 8: for文の基礎（要素を順に表示）
############################################################

for (s in wds) {
  print(s)   # 日本語方位を順に表示
}

for (s in wds) {
  print(wdf[which(wds == s)])  # 各方位の角度を表示
}


############################################################
# Section 9: 風向の角度列を作る
############################################################

df["wddeg"] <- 0   # 新しい列 wddeg（角度）を作成

# df$wd（日本語方位）に応じて wddeg に角度を代入していく
for (s in wds) {
  wdval <- wdf[which(wds == s)]       # その方位の角度を取り出す
  df[df$wd == s, "wddeg"] <- wdval    # 一致する行に角度を代入
}

df   # 風向が度数に変換されたことを確認


############################################################
# Section 10: 可視化（折れ線グラフ）
############################################################

# 気圧の変化
ggplot2::ggplot(df, aes(x = date, y = pre)) +
  ggplot2::geom_line()

# 気温の変化（赤）
ggplot2::ggplot(df, aes(x = date, y = temp)) +
  ggplot2::geom_line(color = "red")

# 風速の変化（青）
ggplot2::ggplot(df, aes(x = date, y = ws)) +
  ggplot2::geom_line(color = "blue")

# 風向の角度（緑）
ggplot2::ggplot(df, aes(x = date, y = wddeg)) +
  ggplot2::geom_line(color = "green")


