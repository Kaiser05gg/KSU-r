############################################################
# Section 1: CSVデータのダウンロード
############################################################

# ここは覚えなくてもOK（講義の定型）
csvurl <- "https://www.cc.kyoto-su.ac.jp/~ogohara/lecture/DataAI_FirstCourse/data.csv"

# data.csv として保存
download.file(csvurl, destfile = "data.csv")


############################################################
# Section 2: ライブラリ読み込み
############################################################

library(tidyverse)  # データ処理とggplotを含む便利セット


############################################################
# Section 3: CSVファイルの読み込み（第1段階）
############################################################

# Shift_JIS でエンコーディングされているため locale を指定
# skip=2 → 最初の2行は説明のため飛ばす
df <- read_csv("data.csv",
               locale = locale(encoding = "Shift_JIS"),
               skip = 2)

df          # データ確認
names(df)   # 列名を確認
ncol(df)    # 列数
dim(df)     # 行数と列数


############################################################
# Section 4: 列番号の抽出（1列おきに3列データが繰り返されている構造）
############################################################

# c(1, 2, 5, 8, 11, ...) のように
# "1列目 + 3列周期" で取り出す
cnum <- c(1, seq(2, ncol(df), by = 3))
cnum  # 取り出す列番号を確認


############################################################
# Section 5: 取り出した列の名前（"那覇...気温" など）を整形
############################################################

cname <- names(df)[cnum]   # 抽出した列名
cname

# 列名が "那覇...気温" など "...“ でつながっているので分割
prenum <- unlist(strsplit(cname, "\\.\\.\\."))

# 偶数番目だけ取り出す（都市名だけになる）
prenum[seq(1, length(prenum), by = 2)]

# これを新しい列名として採用
prename <- prenum[seq(1, length(prenum), by = 2)]
length(prename)

# 先頭の列を "date" に変更して整える
prename[1] <- "date"
prename


############################################################
# Section 6: CSVの再読み込み（必要な列だけ正しい列名で読み込む）
############################################################

df <- read_csv("data.csv",
               locale = locale(encoding = "Shift_JIS"),
               col_select = all_of(cnum),   # 必要な列だけ読み込む
               skip = 5,                    # 余分な説明行を飛ばす
               col_names = FALSE)           # ヘッダなし扱い

# 列名をつける
colnames(df) <- prename

# date列を "YYYY/MM" の形式で日付型に変換
df47 <- type_convert(df, col_types = cols(date = col_date("%Y/%m")))


############################################################
# Section 7: データの確認
############################################################

df47            # 中身
names(df47)     # 列名一覧

# 特定の都市（那覇・名古屋・札幌）だけ抜き出し
df47[, c("date", "那覇", "名古屋", "札幌")]

# 要約統計量（平均/最小/最大など）
summary(df47[, c("那覇", "名古屋", "札幌")])


############################################################
# Section 8: 正規分布のランダムデータ生成（学習用）
############################################################

# 平均4, 標準偏差5 の正規乱数を10個生成
test <- rnorm(10, 4, 5)
test


############################################################
# Section 9: 日本語フォント対策（Colab用）
############################################################

# 日本語が文字化けする環境向け（Colabでは必須）
# 日本語フォント Noto Sans をインストール
system("apt-get install -y fonts-noto-cjk")

# ggplot2 で日本語が使えるようにする設定
theme_set(theme_bw(base_family = "Noto Sans CJK JP"))


############################################################
# Section 10: 折れ線グラフの描画（都道府県の年平均気温の推移）
############################################################

# alpha → 透明度、col → 線の色

g <- ggplot(df47) +
  geom_line(aes(x = date, y = 那覇),   alpha = 0.5, col = "red") +
  geom_line(aes(x = date, y = 名古屋), alpha = 0.5, col = "blue") +
  geom_line(aes(x = date, y = 札幌),   alpha = 0.5, col = "green")

plot(g)

